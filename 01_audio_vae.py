def train_vae_with_dim(latent_dim, epochs=80):
    """Train VAE with specific latent dimension"""
    model = BasicVAE(input_dim=13, latent_dim=latent_dim)
    optimizer = optim.Adam(model.parameters(), lr=0.001)

    print(f"Training VAE with latent_dim={latent_dim}...")
    for epoch in range(epochs):
        recon_x, mu, logvar = model(X_tensor)
        loss = vae_loss(recon_x, X_tensor, mu, logvar, beta=0.001)

        optimizer.zero_grad()
        loss.backward()
        optimizer.step()

        if (epoch + 1) % 40 == 0:
            print(f"  Epoch {epoch+1}/{epochs}, Loss: {loss.item():.4f}")

    return model

def evaluate_latent_space(model, X_data):
    """Evaluate clustering in latent space"""
    with torch.no_grad():
        mu, _ = model.encode(torch.FloatTensor(X_data))
        latent = mu.numpy()

    # Apply K-Means
    kmeans = KMeans(n_clusters=10, random_state=42, n_init=10)
    clusters = kmeans.fit_predict(latent)

    # Calculate metrics
    sil_score = silhouette_score(latent, clusters)
    ch_score = calinski_harabasz_score(latent, clusters)

    return latent, clusters, sil_score, ch_score

