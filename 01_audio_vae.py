kl_losses = []

print(f"Training for {epochs} epochs...")
print("Epoch | Total Loss | Recon Loss | KL Loss")
print("-" * 40)

for epoch in range(epochs):
    # Mini-batch training
    permutation = torch.randperm(len(X_tensor))
    epoch_loss = 0
    epoch_recon = 0
    epoch_kl = 0

    for i in range(0, len(X_tensor), batch_size):
        indices = permutation[i:i+batch_size]
        batch_x = X_tensor[indices]

        # Forward pass
        recon_batch, mu, logvar = model(batch_x)

        # Calculate loss
        recon_loss = nn.MSELoss()(recon_batch, batch_x)
        kl_loss = -0.5 * torch.sum(1 + logvar - mu.pow(2) - logvar.exp())
        loss = recon_loss + 0.001 * kl_loss

        # Backward pass
        optimizer.zero_grad()
        loss.backward()
        optimizer.step()

        epoch_loss += loss.item()
        epoch_recon += recon_loss.item()
        epoch_kl += kl_loss.item()

    # Store losses
    avg_loss = epoch_loss / (len(X_tensor) / batch_size)
    avg_recon = epoch_recon / (len(X_tensor) / batch_size)
    avg_kl = epoch_kl / (len(X_tensor) / batch_size)

    train_losses.append(avg_loss)
    recon_losses.append(avg_recon)
    kl_losses.append(avg_kl)

    if (epoch + 1) % 20 == 0:
        print(f"{epoch+1:5d} | {avg_loss:10.4f} | {avg_recon:10.4f} | {avg_kl:8.4f}")

