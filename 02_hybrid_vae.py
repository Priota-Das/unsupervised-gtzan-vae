def apply_clustering(X, n_clusters=10):
    """Apply different clustering algorithms"""
    results = {}

    # 1. K-Means
    kmeans = KMeans(n_clusters=n_clusters, random_state=42, n_init=10)
    results['K-Means'] = kmeans.fit_predict(X)

    # 2. Agglomerative Clustering
    agglomerative = AgglomerativeClustering(n_clusters=n_clusters,
                                           linkage='ward')
    results['Agglomerative'] = agglomerative.fit_predict(X)

    # 3. DBSCAN (automatically determines clusters)
    # Find appropriate epsilon using k-distance graph
    from sklearn.neighbors import NearestNeighbors
    neighbors = NearestNeighbors(n_neighbors=5)
    neighbors_fit = neighbors.fit(X)
    distances, _ = neighbors_fit.kneighbors(X)
    distances = np.sort(distances[:, -1])

    # Find elbow point (simplified)
    eps = np.percentile(distances, 90)  # 90th percentile as eps

    dbscan = DBSCAN(eps=eps, min_samples=5)
    dbscan_labels = dbscan.fit_predict(X)

    # Convert -1 labels (noise) to separate cluster
    dbscan_labels[dbscan_labels == -1] = np.max(dbscan_labels) + 1
    results['DBSCAN'] = dbscan_labels

    return results

