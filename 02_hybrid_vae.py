def train_vae_model(model, X_data, model_name, epochs=150, lr=0.001):
    """Train a VAE model"""
    print(f"\nTraining {model_name}...")

    if isinstance(model, nn.Sequential):
        # Simple VAE training
        optimizer = optim.Adam(model.parameters(), lr=lr)
        losses = []

        for epoch in range(epochs):
            # Forward pass through simple network
            outputs = model(torch.FloatTensor(X_data))
            mu, logvar = outputs[:, :latent_dim], outputs[:, latent_dim:]

            # Reparameterize
            std = torch.exp(0.5 * logvar)
            eps = torch.randn_like(std)
            z = mu + eps * std

            # Simple decoder (linear)
            recon = nn.Linear(latent_dim, input_dim).to(z.device)(z)

            # Loss
            recon_loss = nn.MSELoss()(recon, torch.FloatTensor(X_data))
            kl_loss = -0.5 * torch.sum(1 + logvar - mu.pow(2) - logvar.exp())
            loss = recon_loss + 0.001 * kl_loss

            optimizer.zero_grad()
            loss.backward()
            optimizer.step()

            losses.append(loss.item())

            if (epoch + 1) % 50 == 0:
                print(f"  Epoch {epoch+1}/{epochs}, Loss: {loss.item():.4f}")

        return model, losses, None, None

    else:
        # Enhanced/Deep VAE training
        optimizer = optim.Adam(model.parameters(), lr=lr)
        train_losses = []
        recon_losses = []
        kl_losses = []

        X_tensor = torch.FloatTensor(X_data)

        for epoch in range(epochs):
            # Forward pass
            recon_x, mu, logvar = model(X_tensor)

            # Loss
            recon_loss = nn.MSELoss()(recon_x, X_tensor)
            kl_loss = -0.5 * torch.sum(1 + logvar - mu.pow(2) - logvar.exp())
            loss = recon_loss + 0.001 * kl_loss

            # Backward pass
            optimizer.zero_grad()
            loss.backward()
            optimizer.step()

            # Store losses
            train_losses.append(loss.item())
            recon_losses.append(recon_loss.item())
            kl_losses.append(kl_loss.item())

            if (epoch + 1) % 50 == 0:
                print(f"  Epoch {epoch+1}/{epochs}, Loss: {loss.item():.4f}")

        return model, train_losses, recon_losses, kl_losses

