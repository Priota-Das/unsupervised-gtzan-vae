def apply_clustering(X, n_clusters=10):
    results = {}
    kmeans = KMeans(n_clusters=n_clusters, random_state=42, n_init=10)
    results['K-Means'] = kmeans.fit_predict(X)

    agglomerative = AgglomerativeClustering(n_clusters=n_clusters, linkage='ward')
    results['Agglomerative'] = agglomerative.fit_predict(X)

    neighbors = NearestNeighbors(n_neighbors=5)
    distances, _ = neighbors.fit(X).kneighbors(X)
    distances = np.sort(distances[:, -1])
    eps = np.percentile(distances, 90)
    dbscan = DBSCAN(eps=eps, min_samples=5)
    dbscan_labels = dbscan.fit_predict(X)
    dbscan_labels[dbscan_labels == -1] = np.max(dbscan_labels) + 1 if np.max(dbscan_labels) >= 0 else 0
    results['DBSCAN'] = dbscan_labels

    return results

