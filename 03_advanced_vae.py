"""#Implement Beta-VAE ( on EnhancedVAE with tunable beta)"""

class BetaVAE(nn.Module):
    """Beta-VAE with tunable beta for disentanglement"""
    def __init__(self, input_dim=63, hidden_dims=[128, 64, 32], latent_dim=20):
        super(BetaVAE, self).__init__()

        # Encoder layers
        encoder_layers = []
        prev_dim = input_dim
        for hidden_dim in hidden_dims:
            encoder_layers.append(nn.Linear(prev_dim, hidden_dim))
            encoder_layers.append(nn.BatchNorm1d(hidden_dim))
            encoder_layers.append(nn.ReLU())
            encoder_layers.append(nn.Dropout(0.2))
            prev_dim = hidden_dim

        self.encoder = nn.Sequential(*encoder_layers)

        # Latent space
        self.fc_mu = nn.Linear(hidden_dims[-1], latent_dim)
        self.fc_logvar = nn.Linear(hidden_dims[-1], latent_dim)

        # Decoder layers
        decoder_layers = []
        decoder_dims = [latent_dim] + hidden_dims[::-1]

        for i in range(len(decoder_dims) - 1):
            decoder_layers.append(nn.Linear(decoder_dims[i], decoder_dims[i+1]))
            decoder_layers.append(nn.BatchNorm1d(decoder_dims[i+1]))
            decoder_layers.append(nn.ReLU())
            decoder_layers.append(nn.Dropout(0.2))

        decoder_layers.append(nn.Linear(decoder_dims[-1], input_dim))
        self.decoder = nn.Sequential(*decoder_layers)

    def encode(self, x):
        h = self.encoder(x)
        return self.fc_mu(h), self.fc_logvar(h)

    def reparameterize(self, mu, logvar):
        std = torch.exp(0.5 * logvar)
        eps = torch.randn_like(std)
        return mu + eps * std

    def decode(self, z):
        return self.decoder(z)

    def forward(self, x):
        mu, logvar = self.encode(x)
        z = self.reparameterize(mu, logvar)
        return self.decode(z), mu, logvar

"""Train Beta-VAE"""

def train_beta_vae(model, X_data, epochs=150, lr=0.001, beta=4.0):
    optimizer = optim.Adam(model.parameters(), lr=lr)
    train_losses = []
    recon_losses = []
    kl_losses = []

    X_tensor = torch.FloatTensor(X_data)

    for epoch in range(epochs):
        recon_x, mu, logvar = model(X_tensor)
        recon_loss = nn.MSELoss()(recon_x, X_tensor)
        kl_loss = -0.5 * torch.sum(1 + logvar - mu.pow(2) - logvar.exp())
        loss = recon_loss + beta * kl_loss

        optimizer.zero_grad()
        loss.backward()
        optimizer.step()

        train_losses.append(loss.item())
        recon_losses.append(recon_loss.item())
        kl_losses.append(kl_loss.item())

        if (epoch + 1) % 50 == 0:
            print(f"  Epoch {epoch+1}/{epochs}, Loss: {loss.item():.4f}, Recon: {recon_loss.item():.4f}, KL: {kl_loss.item():.4f}")

    return model, train_losses, recon_losses, kl_losses

