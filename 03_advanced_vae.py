"""Define cluster purity metric"""

def cluster_purity(y_true, y_pred):
    contingency = pd.crosstab(y_true, y_pred)
    majority = contingency.max(axis=0)
    return majority.sum() / len(y_true)

"""Evaluate clustering with all metrics"""

def evaluate_clustering(X, labels, true_labels):
    metrics = {}
    metrics['Silhouette'] = silhouette_score(X, labels)
    metrics['Davies-Bouldin'] = davies_bouldin_score(X, labels)
    metrics['ARI'] = adjusted_rand_score(true_labels, labels)
    metrics['NMI'] = normalized_mutual_info_score(true_labels, labels)
    metrics['Purity'] = cluster_purity(true_labels, labels)
    return metrics

