import os
import librosa
import numpy as np

print(" PROCESSING GTZAN FROM CORRECT LOCATION")
print("=" * 50)

# Your GTZAN location
GTZAN_PATH = "/content/drive/MyDrive/Data/genres_original"
print(f"GTZAN path: {GTZAN_PATH}")

# Check if it exists
if not os.path.exists(GTZAN_PATH):
    print(f" ERROR: {GTZAN_PATH} not found!")
    print("Make sure you've mounted Google Drive:")
    print("from google.colab import drive")
    print("drive.mount('/content/drive')")
else:
    print(f" GTZAN found at: {GTZAN_PATH}")

    # List genres
    genres = os.listdir(GTZAN_PATH)
    print(f"Found {len(genres)} genres: {genres}")

    # Show first genre structure
    first_genre = os.path.join(GTZAN_PATH, genres[0])
    files = [f for f in os.listdir(first_genre) if f.endswith('.wav')]
    print(f"\nSample: {genres[0]} has {len(files)} .wav files")

# ===== PROCESS ALL GENRES =====
genres = ['blues', 'classical', 'country', 'disco', 'hiphop',
          'jazz', 'metal', 'pop', 'reggae', 'rock']

all_features = []
all_labels = []
processed_count = 0

print("\n PROCESSING AUDIO FILES...")

for genre_id, genre in enumerate(genres):
    genre_path = os.path.join(GTZAN_PATH, genre)

    if not os.path.exists(genre_path):
        print(f" {genre} folder not found at {genre_path}")
        continue

    files = [f for f in os.listdir(genre_path) if f.endswith('.wav')]
    print(f"🎵 {genre}: {len(files)} files")

    # Process each file
    for file_idx, file in enumerate(files):
        try:
            file_path = os.path.join(genre_path, file)

            # Load 30s audio
            y, sr = librosa.load(file_path, duration=30, sr=22050)

            # Extract MFCC features
            mfcc = librosa.feature.mfcc(y=y, sr=sr, n_mfcc=13)
            features = np.mean(mfcc, axis=1)  # 13 features

            all_features.append(features)
            all_labels.append(genre_id)
            processed_count += 1

        except Exception as e:
            print(f"   Error with {file}: {str(e)[:50]}...")
            continue

    print(f"    Processed {len(files)} files")

# Convert to arrays
X_audio = np.array(all_features)  # Should be 1000×13
y_genre = np.array(all_labels)

print(f"\n EXTRACTION COMPLETE!")
print(f"   Processed {processed_count} audio files")
print(f"   Features shape: {X_audio.shape}")
print(f"   Unique genres: {len(np.unique(y_genre))}")

